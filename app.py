@app.get("/api/dashboard")
def dashboard():
    with db() as con:
        customers = con.execute("SELECT COUNT(*) FROM customers").fetchone()[0]
        products = con.execute("SELECT COUNT(*) FROM products").fetchone()[0]
        invoices = con.execute("SELECT COUNT(*) FROM invoices").fetchone()[0]
        revenue = con.execute("SELECT COALESCE(SUM(paid_amount),0) FROM invoices").fetchone()[0]
        outstanding_expr = "GREATEST(subtotal-paid_amount,0)" if USE_POSTGRES else "MAX(subtotal-paid_amount,0)"
        outstanding = con.execute(f"SELECT COALESCE(SUM({outstanding_expr}),0) FROM invoices").fetchone()[0]
        recent = con.execute("""SELECT i.*, c.name customer_name FROM invoices i
                                JOIN customers c ON c.id=i.customer_id ORDER BY i.id DESC LIMIT 5""").fetchall()
        return jsonify({"customers":customers,"products":products,"invoices":invoices,
                        "revenue":revenue,"outstanding":outstanding,"recent":[dict(x) for x in recent]})

