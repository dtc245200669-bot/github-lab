@app.post("/api/invoices/<int:item_id>/payments")
def add_payment(item_id):
    d=request.get_json(silent=True) or {}
    try: amount=float(d.get("amount",0))
    except (TypeError,ValueError): return err("Số tiền không hợp lệ.")
    if amount <= 0: return err("Số tiền thanh toán phải lớn hơn 0.")
    with db() as con:
        inv=con.execute("SELECT * FROM invoices WHERE id=?",(item_id,)).fetchone()
        if not inv: return err("Không tìm thấy hóa đơn.",404)
        due=round(inv["subtotal"]-inv["paid_amount"],2)
        if amount > due + 0.001: return err("Số tiền thanh toán vượt quá số tiền còn nợ.")
        con.execute("INSERT INTO payments(invoice_id,amount,paid_at,method,note) VALUES(?,?,?,?,?)",
                    (item_id,amount,datetime.now().strftime("%Y-%m-%d %H:%M"),d.get("method","Cash"),d.get("note","")))
        paid=round(inv["paid_amount"]+amount,2)
        status="Paid" if paid >= inv["subtotal"]-0.001 else "Partial"
        con.execute("UPDATE invoices SET paid_amount=?,status=? WHERE id=?",(paid,status,item_id))
        return jsonify({"message":"Đã ghi nhận thanh toán.","status":status,"paid_amount":paid})

@app.delete("/api/invoices/<int:item_id>")
def delete_invoice(item_id):
    with db() as con:
        inv=con.execute("SELECT * FROM invoices WHERE id=?",(item_id,)).fetchone()
        if not inv: return err("Không tìm thấy hóa đơn.",404)
        if inv["paid_amount"] > 0: return err("Không thể xóa hóa đơn đã có thanh toán.")
        items=con.execute("SELECT product_id,quantity FROM invoice_items WHERE invoice_id=?",(item_id,)).fetchall()
        for item in items:
            if item["product_id"]:
                con.execute("UPDATE products SET stock=stock+? WHERE id=?",(item["quantity"],item["product_id"]))
        con.execute("DELETE FROM invoices WHERE id=?",(item_id,))
        return jsonify({"message":"Đã xóa hóa đơn và hoàn lại tồn kho."})

