def import_sqlite_data(con, source_path):
    tables = {
        "customers": ("id", "name", "phone", "email", "address", "created_at"),
        "products": ("id", "name", "sku", "price", "stock", "created_at"),
        "invoices": ("id", "invoice_no", "customer_id", "issued_at", "due_date", "subtotal",
                     "paid_amount", "status", "notes"),
        "invoice_items": ("id", "invoice_id", "product_id", "product_name", "quantity",
                          "unit_price", "line_total"),
        "payments": ("id", "invoice_id", "amount", "paid_at", "method", "note"),
    }
    with sqlite3.connect(f"file:{source_path}?mode=ro", uri=True) as source:
        source.row_factory = sqlite3.Row
        available = {row[0] for row in source.execute(
            "SELECT name FROM sqlite_master WHERE type='table'")}
        if not set(tables).issubset(available):
            raise RuntimeError(f"SQLite database at {source_path} does not contain the billing schema.")
        imported = 0
        for table, columns in tables.items():
            column_list = ",".join(columns)
            placeholders = ",".join("?" for _ in columns)
            rows = source.execute(f"SELECT {column_list} FROM {table}").fetchall()
            values = [tuple(row[column] for column in columns) for row in rows]
            for offset in range(0, len(values), 500):
                batch = values[offset:offset + 500]
                con.execute(
                    f"INSERT INTO {table} ({column_list}) VALUES " +
                    ",".join(f"({placeholders})" for _ in batch),
                    tuple(value for row in batch for value in row),
                )
            imported += len(rows)
    for table in tables:
        con.execute(
            f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
            f"COALESCE((SELECT MAX(id) FROM {table}), 1), "
            f"EXISTS (SELECT 1 FROM {table}))"
        )
    logger.info("Imported %s rows from the existing SQLite database.", imported)

def err(message, status=400):
    return jsonify({"error": message}), status

@app.before_request
def start_request_timer():
    request._started_at = time.perf_counter()

@app.after_request
def record_request_metrics(response):
    if request.endpoint != "metrics":
        endpoint = request.endpoint or "unmatched"
        HTTP_REQUESTS.labels(request.method, endpoint, str(response.status_code)).inc()
        HTTP_DURATION.labels(request.method, endpoint).observe(time.perf_counter() - request._started_at)
    return response

