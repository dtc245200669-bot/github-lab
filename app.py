@app.route("/api/invoices", methods=["GET","POST"])
def invoices():
    with db() as con:
        if request.method == "GET":
            q=request.args.get("q","").strip()
            rows=con.execute("""SELECT i.*, c.name customer_name FROM invoices i JOIN customers c ON c.id=i.customer_id
                                WHERE i.invoice_no LIKE ? OR c.name LIKE ? ORDER BY i.id DESC""",
                             (f"%{q}%",f"%{q}%")).fetchall()
            return jsonify([dict(x) for x in rows])
        d=request.get_json(silent=True) or {}
        try: customer_id=int(d.get("customer_id")); items=d.get("items",[])
        except (TypeError,ValueError): return err("Khách hàng không hợp lệ.")
        if not items: return err("Hóa đơn phải có ít nhất một sản phẩm.")
        customer=con.execute("SELECT id FROM customers WHERE id=?", (customer_id,)).fetchone()
        if not customer: return err("Khách hàng không tồn tại.")
        invoice_no="HD-"+datetime.now().strftime("%Y%m%d-%H%M%S-%f")[-19:]
        issued_at=datetime.now().strftime("%Y-%m-%d")
        normalized=[]; subtotal=0
        try:
            for item in items:
                pid=int(item.get("product_id")); qty=int(item.get("quantity"))
                if qty <= 0: return err("Số lượng phải lớn hơn 0.")
                p=con.execute("SELECT * FROM products WHERE id=?", (pid,)).fetchone()
                if not p: return err("Có sản phẩm không tồn tại.")
                if p["stock"] < qty: return err(f"Sản phẩm '{p['name']}' không đủ tồn kho.")
                total=p["price"]*qty; subtotal+=total
                normalized.append((p,qty,total))
        except (TypeError,ValueError,AttributeError):
            return err("Danh sách sản phẩm không hợp lệ.")
        cur=con.execute("""INSERT INTO invoices(invoice_no,customer_id,issued_at,due_date,subtotal,paid_amount,status,notes)
                            VALUES(?,?,?,?,?,0,'Unpaid',?) RETURNING id""",
                        (invoice_no,customer_id,issued_at,d.get("due_date",""),subtotal,d.get("notes","")))
        iid=cur.fetchone()["id"]
        for p,qty,total in normalized:
            con.execute("INSERT INTO invoice_items(invoice_id,product_id,product_name,quantity,unit_price,line_total) VALUES(?,?,?,?,?,?)",
                        (iid,p["id"],p["name"],qty,p["price"],total))
            con.execute("UPDATE products SET stock=stock-? WHERE id=?", (qty,p["id"]))
        return jsonify({"message":"Đã tạo hóa đơn.","id":iid,"invoice_no":invoice_no}),201

